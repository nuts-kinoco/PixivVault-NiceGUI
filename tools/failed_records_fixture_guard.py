"""Reject accidentally targeting another database during failure-list native tests."""
import hashlib
import json
from pathlib import Path


MANIFEST = "synthetic-failure-fixture.json"


def _files(db: Path, images: Path):
    db, images = db.absolute(), images.absolute()
    if db.name != "synthetic-legacy.sqlite" or images != db.parent / "fake-images":
        raise ValueError("explicit synthetic failure fixture required")
    paths = [db, images / "架空保存作者(12)" / "架空作品(101)_1.png",
             images / "架空保存作者(12)" / "架空作品(101)_2.png"]
    if any(path.is_symlink() or not path.is_file() for path in paths):
        raise ValueError("synthetic failure fixture file is missing")
    return paths


def write_fixture_manifest(db: Path, images: Path):
    paths = _files(db, images)
    packet = {"kind": "pixivvault.synthetic.failure-records.v1", "files": {
        path.relative_to(db.parent).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in paths}}
    with (db.parent / MANIFEST).open("x", encoding="utf-8") as stream:
        json.dump(packet, stream, ensure_ascii=False, indent=2)


def verify_fixture_manifest(db: Path, images: Path):
    paths = _files(db, images)
    marker = db.parent / MANIFEST
    if marker.is_symlink() or marker.stat().st_size > 4096:
        raise ValueError("invalid synthetic failure fixture marker")
    packet = json.loads(marker.read_text(encoding="utf-8"))
    expected = {"kind": "pixivvault.synthetic.failure-records.v1", "files": {
        path.relative_to(db.parent).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in paths}}
    if packet != expected:
        raise ValueError("synthetic failure fixture changed or was not generated by this check")
    return True
