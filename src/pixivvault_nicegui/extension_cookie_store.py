"""Offline extension Cookie generations; the borrowed profile CAS alone adopts them.

No browser, HTTP, account verification or application reader is constructed here.
An unadopted generation is retained, never mistaken for an active credential.
The caller owns runtime reader replacement after a successful ``commit``.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
import math
import os
from pathlib import Path
import re
import stat
from threading import RLock
import time
from uuid import uuid4

from .fs_paths import logical_path, native_io_path
from .native_profile import NativeProfileStore, NativeProfileConflict, STORAGE_FOLDER
from .pixiv_read_client import COOKIE_LIMIT, _read_cookies


MARKER = '.pixivvault-extension-credentials.json'
LOCK = '.writer.lock'
MAX_COOKIE_PAYLOAD_BYTES = 2 * 1024 * 1024
MAX_COOKIES = 1024
_MAX_EXPIRY = 253402300799
_TOKEN = re.compile(r'[0-9a-f]{32}\Z')
_SHA = re.compile(r'[0-9a-f]{64}\Z')
_NAME = re.compile(r"[!#$%&'*+.^_`|~0-9A-Za-z-]{1,256}\Z")
_DOMAIN = re.compile(r'\.?[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?\Z')
_HEADER = ('# Netscape HTTP Cookie File\n'
           '# Generated by PixivVault-NiceGUI; immutable credential generation.\n\n')


class CookieSyncError(RuntimeError):
    """Fixed public diagnostic: do not forward parser/OS/profile exception text."""
    code = 'cookie_sync_rejected'
    message = 'Cookie同期の保存を確認できませんでした。'

    def __init__(self):
        super().__init__(self.message)


class CookieSyncConflict(CookieSyncError):
    code = 'cookie_sync_conflict'
    message = 'Cookie同期の対象世代が変更されました。再確認が必要です。'


class CookieSyncBusy(CookieSyncError):
    code = 'cookie_sync_busy'
    message = 'Cookie同期の保存領域は使用中です。'


class CookieSyncCommitUnconfirmed(CookieSyncError):
    code = 'cookie_sync_commit_unconfirmed'
    message = 'Cookie同期の採用結果を確認できません。現在の設定を再確認してください。'


@dataclass(frozen=True, slots=True, eq=False)
class PreparedCookieGeneration:
    changed: bool
    profile_revision: int
    cookie_count: int
    byte_count: int
    cookie_file: Path = field(repr=False)
    sha256: str = field(repr=False)
    generation: str | None = field(repr=False)


@dataclass(frozen=True, slots=True)
class CookieCommit:
    changed: bool
    profile_revision: int
    cookie_count: int
    byte_count: int
    cookie_file: Path = field(repr=False)
    sha256: str = field(repr=False)
    generation: str | None = field(repr=False)


@dataclass(frozen=True, slots=True)
class _SourceProof:
    path: Path = field(repr=False)
    identity: tuple | None = field(repr=False)
    sha256: str | None = field(repr=False)


@dataclass(frozen=True, slots=True)
class _Pending:
    candidate: PreparedCookieGeneration = field(repr=False)
    previous: object = field(repr=False)
    source: _SourceProof | None = field(repr=False)


def _identity(info):
    # Windows lstat and CRT fstat can expose different ctime meanings.
    # Birth time agrees across both; retain file ID, links, size and mtime.
    created = getattr(info, 'st_birthtime_ns', info.st_ctime_ns)
    return (info.st_dev, info.st_ino, info.st_mode, info.st_nlink, info.st_size,
            info.st_mtime_ns, created)


def _safe(path, *, file=False, missing=False):
    path = native_io_path(path)
    leaf = None
    for node in (path, *path.parents):
        try:
            info = node.lstat()
        except FileNotFoundError:
            if node == path and not missing:
                raise CookieSyncError() from None
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, 'st_file_attributes', 0) & 0x400:
            raise CookieSyncError()
        if node == path and file:
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise CookieSyncError()
        elif not stat.S_ISDIR(info.st_mode):
            raise CookieSyncError()
        if node == path:
            leaf = info
    return leaf


def _canonical(value, *, file=False, missing=False):
    if not isinstance(value, (str, Path)) or not str(value) or '\0' in str(value):
        raise CookieSyncError()
    path = Path(value)
    if not path.is_absolute() or '..' in path.parts or path == path.parent:
        raise CookieSyncError()
    _safe(path, file=file, missing=missing)
    path = logical_path(native_io_path(path).resolve(strict=False))
    _safe(path, file=file, missing=missing)
    return path


def _overlap(first, second):
    return first == second or first in second.parents or second in first.parents


def _read_stable(path, limit):
    io_path = native_io_path(path)
    before = _safe(io_path, file=True)
    if before.st_size > limit:
        raise CookieSyncError()
    flags = os.O_RDONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    descriptor = os.open(io_path, flags)
    with os.fdopen(descriptor, 'rb') as stream:
        opened = os.fstat(stream.fileno())
        if _identity(before) != _identity(opened):
            raise CookieSyncError()
        raw = stream.read(limit + 1)
        after = os.fstat(stream.fileno())
    if (len(raw) > limit or len(raw) != before.st_size
            or _identity(after) != _identity(before)
            or _identity(_safe(io_path, file=True)) != _identity(before)):
        raise CookieSyncError()
    return raw, _SourceProof(logical_path(io_path), _identity(before), hashlib.sha256(raw).hexdigest())


def _write_new(path, raw):
    _safe(Path(path).parent)
    flags = os.O_CREAT | os.O_EXCL | os.O_WRONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    descriptor = os.open(native_io_path(path), flags, 0o600)
    with os.fdopen(descriptor, 'wb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise CookieSyncError()
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())
    observed, _ = _read_stable(path, len(raw))
    if observed != raw:
        raise CookieSyncError()


def _fsync_directory(path):
    # Windows file fsync is used above; no power-loss guarantee is inferred for
    # directory metadata from a POSIX-only directory fsync operation.
    if os.name != 'nt':
        descriptor = os.open(native_io_path(path), os.O_RDONLY)
        try:
            os.fsync(descriptor)
        finally:
            os.close(descriptor)


def _json(value):
    return (json.dumps(value, ensure_ascii=True, sort_keys=True,
                       separators=(',', ':'), allow_nan=False) + '\n').encode('ascii')


def _unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CookieSyncError()
        result[key] = value
    return result


def _text(value, maximum, *, empty=False):
    if (type(value) is not str or len(value) > maximum or not empty and not value
            or any(ord(char) < 32 or ord(char) == 127 for char in value)):
        raise CookieSyncError()
    return value


def _key(domain, path, name):
    domain = _text(domain, 253).lower()
    host = domain.removeprefix('.')
    if (not _DOMAIN.fullmatch(domain) or '..' in domain
            or not (host == 'pixiv.net' or host.endswith('.pixiv.net'))):
        raise CookieSyncError()
    path = _text(path, 2048)
    name = _text(name, 256)
    if not path.startswith('/') or not _NAME.fullmatch(name):
        raise CookieSyncError()
    return domain, path, name


def _parse_existing(raw):
    """Bounded semantic comparison, including expired rows; never authentication."""
    text = raw.decode('utf-8-sig')
    lines = [line[:-1] if line.endswith('\r') else line for line in text.split('\n')]
    if not lines or lines[0] not in ('# Netscape HTTP Cookie File', '# HTTP Cookie File'):
        raise CookieSyncError()
    rows = {}
    for line in lines[1:]:
        if line.startswith('#HttpOnly_'):
            line = line[len('#HttpOnly_'):]
        elif line.startswith('#') or not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 7:
            raise CookieSyncError()
        domain, sub, path, secure, expiry, name, value = parts
        key = _key(domain, path, name)
        if (sub not in ('TRUE', 'FALSE') or secure not in ('TRUE', 'FALSE')
                or (sub == 'TRUE') != key[0].startswith('.') or key in rows):
            raise CookieSyncError()
        if expiry == '':
            timestamp = None
        elif re.fullmatch(r'0|[1-9][0-9]{0,11}', expiry) and int(expiry) <= _MAX_EXPIRY:
            timestamp = int(expiry)
        else:
            raise CookieSyncError()
        rows[key] = (_text(value, 16384, empty=True), secure == 'TRUE', timestamp)
        if len(rows) > MAX_COOKIES:
            raise CookieSyncError()
    if not rows:
        raise CookieSyncError()
    return rows


def _normalize(cookies, previous):
    if (type(cookies) is not list or not 1 <= len(cookies) <= MAX_COOKIES
            or any(type(item) is not dict or any(type(key) is not str for key in item) for item in cookies)):
        raise CookieSyncError()
    if len(_json(cookies)) > MAX_COOKIE_PAYLOAD_BYTES:
        raise CookieSyncError()
    now = time.time()
    if type(now) not in (int, float) or not math.isfinite(now) or not 0 < now < _MAX_EXPIRY - 31 * 86400:
        raise CookieSyncError()
    rows = {}
    for item in cookies:
        key = _key(item.get('domain'), item.get('path', '/'), item.get('name'))
        value = _text(item.get('value'), 16384, empty=True)
        secure = item.get('secure', False)
        if type(secure) is not bool or key in rows:
            raise CookieSyncError()
        expiry = item.get('expirationDate')
        if expiry is not None and (type(expiry) not in (int, float) or not math.isfinite(expiry)):
            raise CookieSyncError()
        if expiry is not None and expiry > 0:
            timestamp = int(expiry)
            if not 0 < timestamp <= _MAX_EXPIRY:
                raise CookieSyncError()
        else:
            old = previous.get(key)
            # Original server.py:1087-1092 preserves same-value session expiry;
            # a changed/new session receives the same 12-hour/30-day rounding.
            timestamp = (old[2] if old is not None and old[0] == value and old[2] is not None
                         else (int(now) // 43200) * 43200 + 86400 * 30)
        rows[key] = value, secure, timestamp
    return rows


def _serialize(rows):
    result = _HEADER + ''.join(
        f"{domain}\t{'TRUE' if domain.startswith('.') else 'FALSE'}\t{path}\t"
        f"{'TRUE' if secure else 'FALSE'}\t{expiry}\t{name}\t{value}\n"
        for (domain, path, name), (value, secure, expiry) in sorted(rows.items()))
    raw = result.encode('utf-8')
    if not 0 < len(raw) <= COOKIE_LIMIT:
        raise CookieSyncError()
    return raw


class ExtensionCookieStore:
    """One application owner and one prepared generation; profile is borrowed.

    Published generations and failed stages are immutable retained evidence.
    This owner does not delete old credentials while readers may still use them.
    ``prepare``/``commit`` are blocking local I/O and belong off the UI thread.
    """

    def __init__(self, root, *, profile, protected_roots=()):
        self._guard = RLock()
        self._owner_fd = None
        self._pending = None
        self._closed = False
        try:
            if not isinstance(profile, NativeProfileStore) or type(protected_roots) not in (list, tuple):
                raise CookieSyncError()
            self._profile = profile
            self.root = _canonical(root, missing=True)
            self._profile_root = _canonical(profile.root)
            self._protected = tuple(_canonical(path, missing=True) for path in protected_roots)
            key = lambda path: hashlib.sha256(os.path.normcase(str(path)).encode('utf-8')).hexdigest()
            self._marker_bytes = _json({'application': 'pixivvault-nicegui',
                'purpose': 'extension-cookie-generations', 'version': 1,
                'profile_key': key(self._profile_root), 'root_key': key(self.root)})
            initial = profile.snapshot()
            self._boundaries(initial)
            if _safe(self.root, missing=True) is None:
                _safe(self.root.parent)
                native_io_path(self.root).mkdir(mode=0o700, exist_ok=False)
                _write_new(self.root / MARKER, self._marker_bytes)
                _fsync_directory(self.root)
            raw, self._marker_proof = _read_stable(self.root / MARKER, 4096)
            if raw != self._marker_bytes:
                raise CookieSyncError()
            self._acquire_owner()
            root_info = _safe(self.root)
            self._root_identity = (root_info.st_dev, root_info.st_ino)
            self._generations = self.root / 'generations'
            if _safe(self._generations, missing=True) is None:
                native_io_path(self._generations).mkdir(mode=0o700, exist_ok=False)
                _fsync_directory(self.root)
            folder_info = _safe(self._generations)
            self._generation_identity = (folder_info.st_dev, folder_info.st_ino)
            # Existing owned references must be complete generations. Expired
            # credentials remain structurally valid so a new sync can repair them.
            if initial.cookie_file is not None:
                source = _canonical(initial.cookie_file, file=True, missing=True)
                if source.is_relative_to(self.root):
                    self._owned_generation(source)
        except CookieSyncError:
            self._closed = True
            self._release_owner()
            raise
        except Exception:
            self._closed = True
            self._release_owner()
            raise CookieSyncError() from None

    def _acquire_owner(self):
        path = self.root / LOCK
        _safe(path, file=True, missing=True)
        flags = os.O_CREAT | os.O_RDWR | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0)
        descriptor = os.open(native_io_path(path), flags, 0o600)
        try:
            info = os.fstat(descriptor)
            if (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size not in (0, 1)
                    or _identity(_safe(path, file=True)) != _identity(info)):
                raise CookieSyncError()
            try:
                os.lseek(descriptor, 0, os.SEEK_SET)
                if os.name == 'nt':
                    import msvcrt
                    msvcrt.locking(descriptor, msvcrt.LK_NBLCK, 1)
                else:
                    import fcntl
                    fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                raise CookieSyncBusy() from None
            self._owner_fd = descriptor
            info = os.fstat(descriptor)
            if info.st_size == 0:
                if os.write(descriptor, b'0') != 1:
                    raise CookieSyncError()
                os.fsync(descriptor)
            os.lseek(descriptor, 0, os.SEEK_SET)
            if os.fstat(descriptor).st_size != 1 or os.read(descriptor, 2) != b'0':
                raise CookieSyncError()
            self._owner_identity = _identity(os.fstat(descriptor))
        except BaseException:
            if self._owner_fd is None:
                os.close(descriptor)
            else:
                self._release_owner()
            raise

    def _release_owner(self):
        descriptor, self._owner_fd = self._owner_fd, None
        if descriptor is not None:
            os.close(descriptor)  # Closing the handle releases the OS byte/flock lease.

    def _boundaries(self, snapshot):
        if _canonical(self._profile.root) != self._profile_root:
            raise CookieSyncConflict()
        protected = [self._profile_root, *self._protected]
        if snapshot.save_parent is not None:
            protected.append(_canonical(snapshot.save_parent / STORAGE_FOLDER, missing=True))
        if snapshot.library_readonly_db is not None:
            protected.append(_canonical(snapshot.library_readonly_db, file=True, missing=True).parent)
        if snapshot.library_image_root is not None:
            protected.append(_canonical(snapshot.library_image_root, missing=True))
        if snapshot.cookie_file is not None:
            cookie = _canonical(snapshot.cookie_file, file=True, missing=True)
            if cookie.is_relative_to(self.root):
                # Containment is not ownership. In particular a missing old
                # external reference must not authorize creating this root.
                marker, _ = _read_stable(self.root / MARKER, 4096)
                if marker != self._marker_bytes:
                    raise CookieSyncError()
                self._owned_generation(cookie)
            else:
                protected.append(cookie.parent)
        if any(_overlap(self.root, _canonical(path, missing=True)) for path in protected):
            raise CookieSyncError()

    def _usable(self):
        if self._closed or self._owner_fd is None:
            raise CookieSyncError()
        root_info, folder_info = _safe(self.root), _safe(self._generations)
        if ((root_info.st_dev, root_info.st_ino) != self._root_identity
                or (folder_info.st_dev, folder_info.st_ino) != self._generation_identity):
            raise CookieSyncError()
        raw, marker = _read_stable(self.root / MARKER, 4096)
        if raw != self._marker_bytes or marker != self._marker_proof:
            raise CookieSyncError()
        if (_identity(_safe(self.root / LOCK, file=True)) != self._owner_identity
                or _identity(os.fstat(self._owner_fd)) != self._owner_identity):
            raise CookieSyncError()

    def _owned_generation(self, path):
        path = _canonical(path, file=True)
        relative = path.relative_to(self.root).parts
        if (len(relative) != 3 or relative[0] != 'generations'
                or not _TOKEN.fullmatch(relative[1]) or relative[2] != 'cookies.txt'):
            raise CookieSyncError()
        metadata, _ = _read_stable(path.parent / 'generation.json', 2048)
        packet = json.loads(metadata, object_pairs_hook=_unique)
        if (type(packet) is not dict or set(packet) != {'version', 'generation', 'bytes', 'sha256', 'cookie_count'}
                or type(packet['version']) is not int or packet['version'] != 1
                or packet['generation'] != relative[1]
                or type(packet['bytes']) is not int or not 0 < packet['bytes'] <= COOKIE_LIMIT
                or type(packet['cookie_count']) is not int or not 1 <= packet['cookie_count'] <= MAX_COOKIES
                or type(packet['sha256']) is not str or not _SHA.fullmatch(packet['sha256'])):
            raise CookieSyncError()
        raw, proof = _read_stable(path, COOKIE_LIMIT)
        rows = _parse_existing(raw)
        if (len(raw) != packet['bytes'] or proof.sha256 != packet['sha256']
                or len(rows) != packet['cookie_count'] or raw != _serialize(rows)):
            raise CookieSyncError()
        return raw, proof, rows, relative[1]

    def _previous(self, snapshot):
        if snapshot.cookie_file is None:
            return None, None, {}, None
        path = _canonical(snapshot.cookie_file, file=True, missing=True)
        if path.is_relative_to(self.root):
            return self._owned_generation(path)
        if _safe(path, file=True, missing=True) is None:
            return None, _SourceProof(path, None, None), {}, None
        raw, proof = _read_stable(path, COOKIE_LIMIT)
        try:
            rows = _parse_existing(raw)
        except (CookieSyncError, UnicodeError, ValueError):
            rows = {}  # Invalid old syntax can be replaced, never edited or adopted as valid.
        return raw, proof, rows, None

    def prepare(self, cookies, *, expected_revision):
        with self._guard:
            try:
                self._usable()
                if self._pending is not None:
                    raise CookieSyncBusy()
                if type(expected_revision) is not int or expected_revision < 0:
                    raise CookieSyncConflict()
                previous = self._profile.snapshot()
                if previous.revision != expected_revision:
                    raise CookieSyncConflict()
                self._boundaries(previous)
                old_raw, source, old_rows, generation = self._previous(previous)
                rows = _normalize(cookies, old_rows)
                raw = _serialize(rows)  # Size and every supplied row are checked before mkdir.
                if source is not None and old_rows == rows:
                    candidate = PreparedCookieGeneration(False, expected_revision, len(rows), len(old_raw),
                        previous.cookie_file, source.sha256, generation)
                else:
                    generation = uuid4().hex
                    folder = self._generations / generation
                    _safe(self._generations)
                    native_io_path(folder).mkdir(mode=0o700, exist_ok=False)
                    path = folder / 'cookies.txt'
                    _write_new(path, raw)
                    # Parser only: existing reader contract, no GET and no account claim.
                    _read_cookies(native_io_path(path))
                    metadata = _json({'version': 1, 'generation': generation, 'bytes': len(raw),
                        'sha256': hashlib.sha256(raw).hexdigest(), 'cookie_count': len(rows)})
                    _write_new(folder / 'generation.json', metadata)
                    _fsync_directory(folder)
                    _fsync_directory(self._generations)
                    _raw, checked, _rows, _token = self._owned_generation(path)
                    candidate = PreparedCookieGeneration(True, expected_revision, len(rows), len(raw),
                        logical_path(path), checked.sha256, generation)
                self._usable()
                current = self._profile.snapshot()
                if current != previous:
                    raise CookieSyncConflict()
                self._pending = _Pending(candidate, previous, source)
                return candidate
            except CookieSyncError:
                raise
            except Exception:
                raise CookieSyncError() from None

    def commit(self, candidate):
        with self._guard:
            try:
                if self._pending is None or candidate is not self._pending.candidate:
                    raise CookieSyncConflict()
                pending, self._pending = self._pending, None  # A failed admission cannot be replayed.
                self._usable()
                current = self._profile.snapshot()
                if current != pending.previous:
                    raise CookieSyncConflict()
                self._boundaries(current)
                _raw, previous_proof, _rows, _generation = self._previous(pending.previous)
                if previous_proof != pending.source:
                    raise CookieSyncConflict()
                if candidate.changed:
                    raw, observed, rows, generation = self._owned_generation(candidate.cookie_file)
                    if (observed.sha256 != candidate.sha256 or generation != candidate.generation
                            or len(raw) != candidate.byte_count or len(rows) != candidate.cookie_count):
                        raise CookieSyncConflict()
                    _read_cookies(native_io_path(candidate.cookie_file))
                self._usable()
                # Sole durable commit point. All fallible file/parser checks are
                # before it. No late authentication/close check can undo success.
                try:
                    saved = self._profile.update(cookie_file=candidate.cookie_file,
                                                 expected_revision=candidate.profile_revision)
                except NativeProfileConflict:
                    raise CookieSyncConflict() from None
                except Exception:
                    # A transport/observer must not infer rollback from an
                    # exception after a durable CAS may already have committed.
                    # Do not reread/undo/delete here; an explicit later prepare
                    # observes the profile and can recover a pending publication.
                    raise CookieSyncCommitUnconfirmed() from None
                return CookieCommit(candidate.changed, saved.revision,
                    candidate.cookie_count, candidate.byte_count, candidate.cookie_file,
                    candidate.sha256, candidate.generation)
            except CookieSyncError:
                raise
            except Exception:
                raise CookieSyncError() from None

    def discard(self, candidate):
        with self._guard:
            if self._pending is None or candidate is not self._pending.candidate:
                return False
            self._pending = None
            return True

    def close(self):
        with self._guard:
            if self._closed:
                return
            self._closed = True
            self._pending = None
            try:
                self._release_owner()
            except Exception:
                raise CookieSyncError() from None
