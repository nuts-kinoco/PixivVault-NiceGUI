"""Best-effort startup crash evidence, restricted to the S: drive.

Python exception bodies are never written here. Native faulthandler output is
generated by CPython and contains stack filenames and function names.
"""
from __future__ import annotations

import argparse
from datetime import datetime
import faulthandler
import os
from pathlib import Path
import sys
import threading
import traceback

_active = None


class _Capture:
    def __init__(self, stream):
        self.stream = stream
        self.previous_sys = sys.excepthook
        self.previous_thread = threading.excepthook

    def _write(self, kind, exc_type=None, tb=None, thread=None):
        # Type name and file:line/function only. Exception bodies (which can carry
        # cookies or user data) and directory names are never written.
        try:
            self.stream.write(f'----- 未捕捉の例外 ({kind}) {datetime.now().isoformat()} -----\n')
            if exc_type is not None:
                self.stream.write(f'型: {getattr(exc_type, "__name__", "Exception")}\n')
            if thread is not None:
                self.stream.write(f'スレッド: {getattr(thread, "name", "?")}\n')
            if tb is not None:
                for frame in traceback.extract_tb(tb)[-12:]:
                    self.stream.write(f'  {os.path.basename(frame.filename)}:{frame.lineno} {frame.name}\n')
            self.stream.flush()
        except Exception:
            pass

    def sys_hook(self, exc_type, exc_value, exc_tb):
        try:
            self._write('main', exc_type, exc_tb)
        finally:
            safe_type = next((t for t in (ValueError, TypeError, RuntimeError, OSError) if exc_type is t), RuntimeError)
            try:
                self.previous_sys(safe_type, safe_type('詳細は非表示'), None)
            except BaseException:
                pass

    def thread_hook(self, args):
        try:
            self._write('thread', args.exc_type, args.exc_traceback, args.thread)
        finally:
            safe_type = next((t for t in (ValueError, TypeError, RuntimeError, OSError) if args.exc_type is t), RuntimeError)
            try:
                self.previous_thread(threading.ExceptHookArgs((safe_type, safe_type('詳細は非表示'), None, None)))
            except BaseException:
                pass

    def close(self):
        global _active
        if sys.excepthook == self.sys_hook:
            sys.excepthook = self.previous_sys
        if threading.excepthook == self.thread_hook:
            threading.excepthook = self.previous_thread
        try:
            faulthandler.cancel_dump_traceback_later()
            faulthandler.disable()
        finally:
            self.stream.close()
            if _active is self:
                _active = None


def warn_unavailable():
    try:
        print('警告: クラッシュ記録を保存できません。このまま起動を続けます。', file=sys.stderr)
    except (OSError, ValueError):
        # A windowed launch may have no writable console.
        pass


def install(path=None, *, profile_root=None):
    """Install once under an owned profile or at an explicit S: destination."""
    global _active
    if _active is not None:
        return _active
    stream = None
    try:
        requested = path or os.environ.get('PIXIVVAULT_CRASH_LOG_PATH')
        from .native_profile import PROFILE_IDENTITY, PROFILE_MARKER, _assert_chain, _owned_marker
        if requested:
            target = Path(requested)
        else:
            if profile_root is None:
                parser = argparse.ArgumentParser(add_help=False, allow_abbrev=False, exit_on_error=False)
                parser.add_argument('--profile-root')
                args, _ = parser.parse_known_args()
                profile_root = args.profile_root
            if profile_root is None:
                return None
            root = Path(profile_root)
            if not root.is_absolute() or root.drive.lower() != 's:':
                raise ValueError('invalid profile path')
            if not root.exists():
                # Bootstrap installs the default after creating the owned profile.
                return None
            _owned_marker(root, PROFILE_MARKER, PROFILE_IDENTITY)
            target = root / 'logs' / 'crash_log.txt'
        if not target.is_absolute() or target.drive.lower() != 's:' or '..' in target.parts:
            raise ValueError('invalid crash log path')
        from .test_owner_runtime import require_inside
        require_inside(target)
        _assert_chain(target, kind='file')
        target.parent.mkdir(parents=True, exist_ok=True)
        stream = target.open('a', encoding='utf-8', buffering=1)
        stream.write(f'===== 起動 {datetime.now().isoformat()} pid={os.getpid()} =====\n')
        stream.flush()
        faulthandler.enable(file=stream, all_threads=True)
    except Exception:
        if stream is not None:
            stream.close()
        warn_unavailable()
        return None
    capture = _Capture(stream)
    sys.excepthook = capture.sys_hook
    threading.excepthook = capture.thread_hook
    _active = capture
    if os.environ.get('PIXIVVAULT_ENABLE_PERIODIC_THREAD_DUMP') == '1':
        try:
            faulthandler.dump_traceback_later(300, repeat=True, exit=False, file=stream)
        except Exception:
            pass
    return capture
