"""Former RED: real bootstrap must not bypass an unknown historical STOP.

All credentials, profiles, and HTTP traffic are generated and synthetic.
This is not an authorization to migrate existing profile STOP histories.
"""

import time

import pytest

from pixivvault_nicegui.bootstrap import _build_owned_media_readers
from pixivvault_nicegui.managed_network_stop_gate import (
    ManagedNetworkStopped, ManagedNetworkGateStorageError,
)
from pixivvault_nicegui.managed_network_stop_profile_scope import ManagedProfileNetworkStopScope
from pixivvault_nicegui.native_profile import NativeProfileStore
from pixivvault_nicegui.pixiv_read_client import LivePixivReadClient


@pytest.mark.parametrize("status", (401, 403, 429))
@pytest.mark.parametrize("cli_root", (None, "fresh-generated-root"))
def test_native_stop_must_block_real_bootstrap_profileless_cli_reader(
    tmp_path, monkeypatch, status, cli_root,
):
    credential_dir = tmp_path / "generated-credential"
    credential_dir.mkdir()
    cookie = credential_dir / "synthetic-cookie.txt"
    cookie.write_text(
        "# Netscape HTTP Cookie File\n"
        f".pixiv.net\tTRUE\t/\tTRUE\t{int(time.time()) + 86400}"
        "\tPHPSESSID\t55_generatedonly\n",
        encoding="utf-8",
    )
    profile = tmp_path / "generated-profile"
    store = NativeProfileStore(profile)
    store.close()
    scope = ManagedProfileNetworkStopScope(profile)
    store = NativeProfileStore(profile)
    try:
        store.update(cookie_file=cookie, expected_revision=0)
    finally:
        store.close()
    scope.gate.trip(status)

    calls = []

    class SyntheticOwnedTransport:
        revocation_unverified = False

        def __call__(self, request, *_):
            assert request.get_method() == "GET" and request.data is None
            calls.append("synthetic GET")
            return b"generated bytes"

        def close(self):
            pass

    import pixivvault_nicegui.pixiv_read_client as reader_module
    import pixivvault_nicegui.managed_network_stop_reader as managed_reader_module

    monkeypatch.setattr(reader_module, "_OwnedReadTransport", SyntheticOwnedTransport)
    # If production is later corrected to call create_exact_managed_read_client,
    # its imported alias must ALSO remain synthetic. The RED suite must never
    # become a real network probe merely because bootstrap wiring changes.
    monkeypatch.setattr(managed_reader_module, "_OwnedReadTransport", SyntheticOwnedTransport)
    with pytest.raises(ManagedNetworkGateStorageError):
        _build_owned_media_readers(
            pixiv_cookie_file=cookie,
            pixiv_download_root=(tmp_path / cli_root) if cli_root else None,
            novel_download_root=None,
            novel_fixture_root=None,
            novel_source=None,
            ugoira_root=None,
            ugoira_fixture_root=None,
            live_client=None,
            managed_network_stop_scope=None,
            shared_network_stop_scope=None,
        )
    assert calls == [], "unknown historical Native STOP cannot be bypassed"
    assert scope.gate.snapshot().status_code == status
